"""Generate a reproducible inventory of canonical graph and relation artifacts."""
from __future__ import annotations

import json
import sqlite3
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "Clarion-Backend"
GRAPH_DIR = BACKEND / "data" / "graphs"
DATASET_DIR = BACKEND / "data" / "datasets"
DB_PATH = BACKEND / "data" / "relation_dataset.db"
OUT = ROOT / "GRAPH_ARTIFACT_REGISTRY.md"


def candidate_count(document_id: str) -> int:
    with sqlite3.connect(DB_PATH) as connection:
        return int(connection.execute(
            "SELECT COUNT(*) FROM relation_dataset WHERE document_id = ?", (document_id,)
        ).fetchone()[0])


def document_name(document_id: str) -> str:
    matches = sorted(DATASET_DIR.glob(f"*_{document_id}_relations.json"))
    return matches[0].name.removesuffix("_relations.json") if matches else "(no dataset snapshot)"


def main() -> None:
    rows = []
    for path in sorted(GRAPH_DIR.glob("*.json")):
        if path.name.endswith("_cytoscape.json"):
            continue
        document_id = path.stem
        graph = json.loads(path.read_text(encoding="utf-8"))
        nodes = graph.get("nodes", [])
        edges = graph.get("edges", graph.get("links", []))
        structural = sum(edge.get("relation_type") == "hierarchy" or edge.get("type") == "hierarchy" for edge in edges)
        rows.append((document_name(document_id), document_id, document_id, len(nodes), structural, len(edges) - structural, len(edges), candidate_count(document_id)))

    lines = [
        "# Graph Artifact Registry",
        "",
        "Generated by `scripts/generate_graph_artifact_registry.py` from `Clarion-Backend/data/graphs` and `Clarion-Backend/data/relation_dataset.db`. A graph UUID is its document/run UUID; no independent run manifest exists, so timestamps and code revisions cannot be reconstructed.",
        "",
        "| Document | Run ID | Graph UUID | Nodes | Structural edges | Semantic edges | Total graph edges | Candidate records |",
        "|---|---|---|---:|---:|---:|---:|---:|",
    ]
    lines.extend("| {} | {} | {} | {} | {} | {} | {} | {} |".format(*row) for row in rows)
    lines.extend(["", "## Interpretation", "", "Candidate records are relation-dataset rows, not graph edges. Their counts may differ from graph semantic edges because graph construction filters or aggregates candidates.", ""])
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(rows)} graph artifacts)")


if __name__ == "__main__":
    main()
